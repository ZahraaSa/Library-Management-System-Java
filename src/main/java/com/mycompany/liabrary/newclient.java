    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
       // trim to clear spaces
        String firstname = jTextField1.getText().trim();
        String lastname = jTextField2.getText().trim();
        String phone = jTextField3.getText().trim();
        String address = jTextField4.getText().trim();
        String genderStr = (String) jComboBox1.getSelectedItem();
        String s = null;
        
        if (firstname.isEmpty() || lastname.isEmpty() || phone.isEmpty() ||  address.isEmpty() || genderStr.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill all required fields (Name, Address, Phone, Gender).", "Input Error", JOptionPane.ERROR_MESSAGE);
       return;
        }
        
        if (!jCheckBox1.isSelected()) {
        JOptionPane.showMessageDialog(this, "You must agree to the Terms and Conditions to register the client.", "Registration Error", JOptionPane.ERROR_MESSAGE);
              return;
        }
        if (jCheckBox2.isSelected()) s="active";
        else s="inactive";
    
      char genderChar;
        try {
            genderChar = genderStr.trim().toUpperCase().charAt(0);
            
            if (genderChar != 'M' && genderChar != 'F') {
                 JOptionPane.showMessageDialog(this, "Invalid gender selection.", "Input Error", JOptionPane.ERROR_MESSAGE);
                 return;
            }
            
        } catch (StringIndexOutOfBoundsException e) {
             JOptionPane.showMessageDialog(this, "Please select a valid gender.", "Input Error", JOptionPane.ERROR_MESSAGE);
             return;
        }
       
           try {

            Client newClient = new Client(address,s,firstname,lastname, genderChar, phone );
            
            LibraryApp.library.addClient(newClient); 

JOptionPane.showMessageDialog(this,"Client successfully added! Client ID:"+newClient.getId(),"Success", JOptionPane.INFORMATION_MESSAGE);
            this.dispose(); 
            //to main menu 
            new MainMenuForm().setVisible(true);
            
        } catch (Exception ex) {
JOptionPane.showMessageDialog(this, "An error occurred while adding the client: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);        }
            
       
    }//GEN-LAST:event_jButton1ActionPerformed

