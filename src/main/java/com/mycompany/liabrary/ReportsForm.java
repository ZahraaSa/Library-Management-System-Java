private void loadPopularBooks() {
        popularBooksModel.setRowCount(0);
        
        ArrayList<Book> sortedBooks = LibraryApp.library.getBooksSortedByPopularity();
        
        for (Book book : sortedBooks) {
            Object[] row = {
                book.getId(),
                book.getName(),
                book.getAuthorName(),
                book.getNumberOfSoldCopies() + book.getNumberOfRentedCopies()
            };
            popularBooksModel.addRow(row);
        }
    }

    private void loadOverdueClients() {
        overdueClientsModel.setRowCount(0);
        
        ArrayList<Client> overdue = LibraryApp.library.getOverdueClients();
        
        for (Client client : overdue) {
            Object[] row = {client.getId(),client.getFirstName() + " " + client.getLastName(), client.getPhone()};
            overdueClientsModel.addRow(row);
        }
    }
   
